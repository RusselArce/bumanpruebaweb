-- 1) Propina en ventas
alter table public.ventas
  add column if not exists propina numeric not null default 0;

-- 2) Modificadores (ej: "sin cebolla", "extra queso")
create table if not exists public.modificadores (
  id bigint generated by default as identity primary key,
  id_empresa bigint references public.empresa(id) on delete cascade,
  nombre text not null,
  precio_extra numeric not null default 0,
  state boolean not null default true
);

-- 3) Relación producto <-> modificadores disponibles para ese producto
create table if not exists public.producto_modificadores (
  id bigint generated by default as identity primary key,
  id_producto bigint not null references public.productos(id) on delete cascade,
  id_modificador bigint not null references public.modificadores(id) on delete cascade,
  unique (id_producto, id_modificador)
);

-- 4) Snapshot de modificadores elegidos en cada línea de venta
alter table public.detalle_venta
  add column if not exists modificadores jsonb;
